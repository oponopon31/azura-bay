// AZURA BAY — seeded RNG (round 7 re-compose, written fresh under r7).
// Deterministic mulberry32 + helpers. Used by stunts, events, world
// generation, and the selftest so every run is reproducible from a seed.

export function hashSeed(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher–Yates shuffle with a supplied RNG function; returns a new array.
export function shuffle(arr, rand) {
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = out[i]; out[i] = out[j]; out[j] = tmp;
  }
  return out;
}

export function pick(arr, rand) { return arr[Math.floor(rand() * arr.length)]; }
export function intBetween(rand, lo, hi) { return lo + Math.floor(rand() * (hi - lo + 1)); }
