// ---- Validation helper (used by the self-test) ----
export function validateStory() {
  const problems = [];
  if (STORY.length !== 91) problems.push(`expected 91 missions, got ${STORY.length}`);
  const ids = new Set();
  for (const m of STORY) {
    if (ids.has(m.id)) problems.push(`duplicate id ${m.id}`);
    ids.add(m.id);
    if (m.id < 1 || m.id > 91) problems.push(`id ${m.id} out of range`);
    if (!m.title) problems.push(`mission ${m.id}: no title`);
    if (m.who !== 'lucia' && m.who !== 'jason') problems.push(`mission ${m.id}: bad playable '${m.who}'`);
    if (!['drive', 'steal', 'delivery', 'fetch', 'tail', 'escape', 'heist', 'combat', 'chase', 'timed'].includes(m.type)) problems.push(`mission ${m.id}: bad type '${m.type}'`);
    if (!m.objective) problems.push(`mission ${m.id}: no objective`);
    if (!(m.reward > 0)) problems.push(`mission ${m.id}: no reward`);
    if (!ZONES[m.zone]) problems.push(`mission ${m.id}: bad zone '${m.zone}'`);
    if (!m.contact) problems.push(`mission ${m.id}: no contact`);
    if (!m.beat) problems.push(`mission ${m.id}: no story beat`);
    const ch = CHAPTERS.find((c) => m.id >= c.from && m.id <= c.to);
    if (!ch || ch.n !== m.ch) problems.push(`mission ${m.id}: chapter mismatch`);
  }
  return problems;
}

// ---- Round 3: chapter helpers (HUD chapter screen + debug snapshot) ----
export function missionsInChapter(n) {
  return STORY.filter((m) => m.ch === n);
}

export function chapterReward(n) {
  return missionsInChapter(n).reduce((sum, m) => sum + m.reward, 0);
}
